import pandas as pd
import numpy as np
import pathlib
import json
from sklearn.model_selection import StratifiedShuffleSplit

pathlib.Path("data").mkdir(exist_ok=True)
pathlib.Path("reports").mkdir(exist_ok=True)

parquet_files = list(pathlib.Path(".").rglob("valid.parquet"))
if not parquet_files:
    parquet_files = list(pathlib.Path("/").rglob("valid.parquet"))

if parquet_files:
    file_path = parquet_files[0]
    df = pd.read_parquet(file_path)
    n_valid = len(df)
    print(f" The file has been found at the path: {file_path}")
    print(f"Processing {n_valid:,} rows of CFPB data...")
else:
    raise FileNotFoundError(" The file valid.parquet was not found. Make sure it exists in the working directory.")

text_col = "consumer_complaint_narrative"
target_col = "product"

df = df.drop_duplicates(subset=[text_col, target_col]).reset_index(drop=True)
n_exact = n_valid - len(df)

sss = StratifiedShuffleSplit(n_splits=1, test_size=0.20, random_state=42)
for tr_idx, te_idx in sss.split(df, df[target_col]):
    pass

df["split"] = "train"
df.loc[te_idx, "split"] = "test"
df["group_id"] = np.arange(len(df))

report = {
    "rows_valid": n_valid,
    "exact_duplicates_removed": int(n_exact),
    "split_method": "StratifiedShuffleSplit",
    "train_rows": int((df.split == "train").sum()),
    "test_rows": int((df.split == "test").sum())
}

pathlib.Path("reports/split_report.json").write_text(json.dumps(report, indent=2, ensure_ascii=False), encoding="utf-8")
df.drop(columns=["split", "group_id"], errors="ignore").to_parquet("clean.parquet", index=False)
df.drop(columns=["split", "group_id"], errors="ignore").to_parquet("data/clean.parquet", index=False)
df[['complaint_id', 'group_id', 'split']].to_csv("split_ids.csv", index=False)
df[['complaint_id', 'group_id', 'split']].to_csv("data/split_ids.csv", index=False)

print("The splitting process was successful and all the files were generated with correct and balanced proportions! The files")
print(f"Number of training rows(Train): {report['train_rows']:,}")
print(f"Number of testing rows(Test): {report['test_rows']:,}")

