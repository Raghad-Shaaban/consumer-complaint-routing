import pandas as pd
import pathlib
import json
import matplotlib.pyplot as plt
import seaborn as sns

pathlib.Path("reports").mkdir(exist_ok=True)

file_path = "clean.parquet"
df = pd.read_parquet(file_path)
print(f" The file has been found and successfully uploaded! Number of rows: {len(df):,}")

target_col = "product"
print(f" Checking the labels for the column: {target_col}")

label_counts = df[target_col].value_counts()
label_percentages = df[target_col].value_counts(normalize=True) * 100

audit_summary = pd.DataFrame({
    "count": label_counts,
    "percentage (%)": label_percentages.round(2)
}).reset_index()
audit_summary.columns = [target_col, "count", "percentage"]

report_data = {
    "total_samples": len(df),
    "unique_labels": int(df[target_col].nunique()),
    "label_distribution": audit_summary.to_dict(orient="records")
}

pathlib.Path("reports/label_audit_report.json").write_text(
    json.dumps(report_data, indent=2, ensure_ascii=False), encoding="utf-8"
)
audit_summary.to_csv("reports/label_audit_summary.csv", index=False)

plt.figure(figsize=(12, 6))
sns.countplot(data=df, y=target_col, order=df[target_col].value_counts().index, palette="viridis")
plt.title("Distribution of Complaint Products (Label Audit)")
plt.xlabel("Number of Samples")
plt.ylabel("Product Category")
plt.tight_layout()
plt.savefig("reports/label_distribution.png", dpi=300)
plt.show()

print(" The audit step has been completed and all reports and charts have been generated successfully!")

