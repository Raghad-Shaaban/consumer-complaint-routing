import pandas as pd
import pathlib
import json
from sklearn.model_selection import StratifiedKFold

file_path = "clean.parquet"
df = pd.read_parquet(file_path)
target_col = "product"

print(f"Number of rows {len(df):,}")

pathlib.Path("reports").mkdir(exist_ok=True)

label_counts = df[target_col].value_counts()
label_percentages = df[target_col].value_counts(normalize=True) * 100

audit_summary = pd.DataFrame({
    target_col: label_counts.index,
    "count": label_counts.values,
    "percentage": label_percentages.values.round(2)
})

report_data = {
    "total_samples": len(df),
    "unique_labels": int(df[target_col].nunique()),
    "label_distribution": audit_summary.to_dict(orient="records")
}

pathlib.Path("reports/label_audit_report.json").write_text(
    json.dumps(report_data, indent=2, ensure_ascii=False), encoding="utf-8"
)
audit_summary.to_csv("reports/label_audit_summary.csv", index=False)

n_splits = 5
skf = StratifiedKFold(n_splits=n_splits, shuffle=True, random_state=42)

df["fold"] = -1
for fold_idx, (train_idx, val_idx) in enumerate(skf.split(df, df[target_col])):
    df.loc[val_idx, "fold"] = fold_idx

split_records = []
for idx, row in df.iterrows():
    split_records.append({
        "index": idx,
        "fold": int(row["fold"]),
        "split": f"fold_{int(row['fold'])}"
    })

split_ids_df = pd.DataFrame(split_records)
split_ids_df.to_csv("split_ids.csv", index=False)

print("Done successfully !")

